DATASETS = {
    'HEALTH': (HEALTH_CATEGORIES, HEALTH_TOPICS),
    'FOOD': (FOOD_CATEGORIES, FOOD_TOPICS),
    'TRAVEL': (TRAVEL_CATEGORIES, TRAVEL_TOPICS),
}


class Command(BaseCommand):
    help = (
        'ContentCalendarTheme/ContentCalendarTopic 최초 데이터를 적재합니다(건강/의학, 음식/영양, '
        '여행/관광). get_or_create 기반이라 재실행해도 안전하며, 이미 있는 행은 건드리지 않습니다.'
    )

    def handle(self, *args, **options):
        for category, (categories, topics) in DATASETS.items():
            for _wd, _lst in topics.items():
                assert len(_lst) == 52, f"{category} weekday {_wd} topic count != 52 ({len(_lst)})"

            theme_created = 0
            for weekday, cat in categories.items():
                _, created = ContentCalendarTheme.objects.get_or_create(
                    category=category, weekday=weekday,
                    defaults=dict(
                        key=cat['key'], name=cat['name'], am_angle=cat['am_angle'], pm_angle=cat['pm_angle'],
                        am_title_template=cat['am'], pm_title_template=cat['pm'],
                    ),
                )
                theme_created += int(created)

            topic_created = 0
            for weekday, topic_list in topics.items():
                for week_number, topic in enumerate(topic_list):
                    _, created = ContentCalendarTopic.objects.get_or_create(
                        category=category, weekday=weekday, week_number=week_number,
                        defaults=dict(topic=topic),
                    )
                    topic_created += int(created)

            self.stdout.write(self.style.SUCCESS(
                f"[{category}] 테마 {theme_created}건, 주제 {topic_created}건 생성 완료."
            ))
