SESSION_LABELS = {'am': '오전', 'pm': '오후'}


def get_topic_for_date(d, session):
    """주어진 날짜(d)·세션('am'|'pm')에 해당하는 (카테고리명, 주제, 제목, 각도라벨)을 계산한다.
    health_calendar.get_topic_for_date와 완전히 같은 계산 방식."""
    if session not in SESSION_LABELS:
        raise ValueError(f"unknown session: {session!r}")

    days_since_start = max((d - START).days, 0)
    cycle_day = days_since_start % CYCLE_DAYS
    cycle_date = START + datetime.timedelta(days=cycle_day)
    weekday = cycle_date.weekday()
    occurrence = cycle_day // 7

    cat = CATEGORIES[weekday]
    topic = TOPICS[weekday][occurrence]
    if session == 'am':
        title = cat['am'].format(t=topic)
        angle = cat['am_angle']
    else:
        title = cat['pm'].format(t=topic)
        angle = cat['pm_angle']
    return dict(category_name=cat['name'], topic=topic, title=title, angle=angle)


def build_one_cycle():
    """52주(364일) 전체를 (날짜, 요일, 카테고리명, 오전 제목, 오후 제목) 리스트로 펼친다.
    generate_food_briefing/관리자 화면 등 내부용으로만 쓴다 — 공개 페이지(/food-calendar/)는
    전체 스케줄이 그대로 퍼가기 당하지 않도록 build_sample()의 요약본만 보여준다."""
    weekday_kr = ["월", "화", "수", "목", "금", "토", "일"]
    rows = []
    for i in range(CYCLE_DAYS):
        d = START + datetime.timedelta(days=i)
        am = get_topic_for_date(d, 'am')
        pm = get_topic_for_date(d, 'pm')
        rows.append(dict(
            date=d, weekday=weekday_kr[d.weekday()], category_name=am['category_name'],
            am_title=am['title'], pm_title=pm['title'],
        ))
    return rows


def build_sample():
    """요일(카테고리)별로 예시 1개씩(그 요일의 첫 번째 주제)만 뽑아 7건을 반환한다 —
    health_calendar.build_sample과 같은 목적/구조."""
    weekday_kr = ["월", "화", "수", "목", "금", "토", "일"]
    rows = []
    for wd in range(7):
        offset = (wd - START.weekday()) % 7
        d = START + datetime.timedelta(days=offset)
        am = get_topic_for_date(d, 'am')
        pm = get_topic_for_date(d, 'pm')
        rows.append(dict(
            weekday=weekday_kr[wd], category_name=am['category_name'],
            am_title=am['title'], pm_title=pm['title'],
        ))
    return rows
